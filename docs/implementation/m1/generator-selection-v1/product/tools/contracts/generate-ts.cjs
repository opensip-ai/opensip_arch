// Closed-registry adapter. The parent verifies and snapshots every input first.
const fs = require('node:fs');
const path = require('node:path');
const {renderTypes} = require('./render-types.cjs');
const [input, output] = process.argv.slice(2);
if (!input || !output || process.argv.length !== 4) throw new Error('input and output roots required');
const prepared = JSON.parse(fs.readFileSync(path.join(input,'ts-projection.json')));
const options = JSON.parse(fs.readFileSync(path.join(input,'options.json')));
if (options.reportEntryPoint !== "urn:opensip:product-v1:workflows:evaluator3:report-projection:1#") throw new Error('unselected report codec root');
const names = new Map(options.entryPoints.map(row=>[row.ref,row.typeName]));
const providerNames = options.providerEntryPoints.map(ref=>{
  if (!names.has(ref)) throw new Error('provider entrypoint missing owner');
  return names.get(ref);
});
const provider = renderTypes(prepared,providerNames);
const report = renderTypes(prepared,[...names.values()]);
const provenance = JSON.parse(fs.readFileSync(path.join(input,'provenance.json')));
const header = '// Generated by contracts-v1; inert carriers, not admission.\n'
  +'// Registry SHA-256: '+provenance.registrySha256+'\n'
  +'// Generator closure SHA-256: '+provenance.generatorClosureSha256+'\n';
function write(relative, text) {
 const file = path.join(output,relative);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,text);
}
write('providers/typescript/src/generated/protocol.ts',header
 +'export type Json = null | boolean | bigint | string | Json[] | {[key:string]:Json};\n'+provider.text);
const runtimeText=['exact-json.ts','patterns.ts','schema.ts'].map(name=>fs.readFileSync(path.join(__dirname,'runtime',name),'utf8').replace(/^import .*;\n/gm,'')).join('\n');
const rawSchemas=JSON.parse(fs.readFileSync(path.join(input,'raw-schemas.json')));
write('apps/report/src/generated/report.ts',header+report.text+'\n'+runtimeText
 +'\nconst selectedSchemaBytes: string[] = '+JSON.stringify(rawSchemas)+';\n'
 +'const selectedSchemaEntryPoints: readonly string[] = '+JSON.stringify([...names.keys()])+';\n'
 +'export function createReportShapeRegistry(): Pick<SchemaRegistry, "matches" | "checkEntryPoints"> {\n'
 +'  const registry = new SchemaRegistry(selectedSchemaBytes.map(raw => parseExact(new TextEncoder().encode(raw))));\n'
 +'  const allowed = new Set(selectedSchemaEntryPoints);\n'
 +'  const checkEntryPoints = (refs: readonly string[]): void => { for (const ref of refs) { if (!allowed.has(ref)) throw new SchemaError("unselected report schema entrypoint"); } registry.checkEntryPoints(refs); };\n'
 +'  return Object.freeze({checkEntryPoints, matches(ref: string, value: Json, limit = 1_000_000): boolean { checkEntryPoints([ref]); return ref === "urn:opensip:product-v1:workflows:evaluator3:report-projection:1#" ? registry.matchesReportProjection(value, limit) : registry.matches(ref, value, limit); }});\n'
 +'}\n');
console.log(JSON.stringify({providerExports:provider.names.length,reportExports:report.names.length,numberTypes:provider.numberTypes+report.numberTypes,anyTypes:provider.anyTypes+report.anyTypes}));
