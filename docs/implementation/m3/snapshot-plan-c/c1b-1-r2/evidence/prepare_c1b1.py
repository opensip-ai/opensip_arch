"""C1b-1 r2 preparation, on the candidate worktree at product main (re-runnable): the census closure re-pin of
custody/git_tracking.rs (discovery_census.py CLOSURE, C1b plan r6 LD-C1B-7), then every output the unit's inputs move,
regenerated by the tools' own --write modes over the lead-readable cache (which never open a held-out store): the
snapshot charge model's three vector files, the discovery census and its vectors, the workspace ledger, and the
snapshot census. The two receipts are never written. It then requires the candidate's changed and new paths to be
exactly the unit's. Usage: prepare_c1b1.py <out json>."""
from pathlib import Path
import hashlib, json, os, re, subprocess, sys
A = Path('/Users/sb/code/opensip-ai/opensip_arch'); P = A.parent / 'opensip'; W = A.parent / 'opensip-c1b1'
PY = '/opt/homebrew/Cellar/python@3.14/3.14.6/bin/python3.14'
T2 = '/Users/sb/code/.opensip-implementation-cache/t2-corpus-c8cc48e1'
GT = 'crates/security/src/custody/git_tracking.rs'; CENSUS = 'tools/security/discovery_census.py'
RECEIPTS = ('crates/security/src/custody/discovery_census_held_out.json', 'crates/security/src/snapshot_ledger_census_held_out.json')
EXPECTED = sorted([
    'crates/security/src/custody/discovery_census.json', 'crates/security/src/custody/discovery_census_vectors.json',
    'crates/security/src/custody/discovery_workspace_ledger.json', GT,
    'crates/security/src/lib.rs', 'crates/security/src/snapshot_ledger_census.json', 'crates/security/src/snapshot_ledger_vectors.json',
    'crates/security/src/snapshot_source.rs', 'crates/security/src/snapshot_vcs.rs', 'crates/security/src/snapshot_vcs_tests.rs',
    'crates/security/src/snapshot_vcs_vectors.json', CENSUS, 'tools/security/snapshot_ledger_model.py'])
NEW = sorted(['crates/security/src/snapshot_vcs.rs', 'crates/security/src/snapshot_vcs_tests.rs', 'crates/security/src/snapshot_vcs_vectors.json'])
E = dict(os.environ, GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL='/dev/null')
for k in ('GIT_CONFIG_COUNT', 'GIT_DIR', 'GIT_WORK_TREE'): E.pop(k, None)
def git(root, *a): return subprocess.check_output(['/usr/bin/git', *a], cwd=root, env=E).decode().strip()
def pin(root, p): raw = (root / p).read_bytes(); return dict(path=p, bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest())
assert git(W, 'rev-parse', 'HEAD') == git(P, 'rev-parse', 'HEAD'), 'rebuild the worktree on main first'
receipts = {r: (W / r).read_bytes() for r in RECEIPTS}
# 1. The closure re-pin: the one CLOSURE row for git_tracking.rs, to the candidate's bytes.
raw = (W / GT).read_bytes(); text = (W / CENSUS).read_text()
row = r"\('crates/security/src/custody/git_tracking\.rs', \d+, '[0-9a-f]{64}'\)"
assert len(re.findall(row, text)) == 1
(W / CENSUS).write_text(re.sub(row, "('%s', %d, '%s')" % (GT, len(raw), hashlib.sha256(raw).hexdigest()), text))
# 2. The regeneration, in dependency order: the model reads the census's closure, the census records bind both tools.
steps = [[PY, '-I', '-B', 'tools/security/snapshot_ledger_model.py', '--write', '--architecture', str(A), '--packages-root', str(P)]]
for tool in ('discovery_census', 'discovery_workspace_ledger', 'snapshot_ledger_census'):
    steps.append([PY, '-I', '-B', 'tools/security/%s.py' % tool, '--write', '--architecture', str(A), '--packages-root', str(P), '--t2-cache', T2])
logs = []
for cmd in steps:
    r = subprocess.run(cmd, cwd=W, env=E, capture_output=True)
    assert r.returncode == 0, (cmd, r.stderr[-2000:])
    logs.append(dict(command=cmd[3], stdout=r.stdout.decode()[-600:]))
for r, b in receipts.items(): assert (W / r).read_bytes() == b, r
# 3. Exactly the unit's paths.
changed = sorted(git(W, 'diff', '--name-only').splitlines() + git(W, 'ls-files', '--others', '--exclude-standard').splitlines())
new = sorted(git(W, 'ls-files', '--others', '--exclude-standard').splitlines())
out = dict(productBase=git(W, 'rev-parse', 'HEAD'), closureRow=pin(W, GT), steps=logs, changed=changed, new=new,
           receiptsUnchanged=True, passed=changed == EXPECTED and new == NEW, candidates=[pin(W, p) for p in changed])
Path(sys.argv[1]).write_text(json.dumps(out, indent=2) + '\n')
print(json.dumps(dict(productBase=out['productBase'], changed=len(changed), new=new, passed=out['passed'])))
raise SystemExit(0 if out['passed'] else 1)
