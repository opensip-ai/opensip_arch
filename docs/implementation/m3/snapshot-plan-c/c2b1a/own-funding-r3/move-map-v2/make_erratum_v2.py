"""Write the MOVE-MAP erratum (LD-Q-125 condition 3) from the move maps, the identity outputs and the citation output.
Usage: make_erratum.py <out.md> <section title>=<map.json>=<identity.txt> ... --citations <citations.txt>..."""
import json
import sys
from pathlib import Path

args = sys.argv[2:]
cites = []
premises = None
if '--premises' in args:
    k = args.index('--premises')
    premises, args = args[k + 1:k + 3], args[:k] + args[k + 3:]
if '--citations' in args:
    k = args.index('--citations')
    cites, args = args[k + 1:], args[:k]
out = ['# MOVE-MAP erratum (LD-Q-125 B1, LD-Q-126): the law-class verbatim move, mechanical',
       '',
       '**Status:** v2, answering REVIEW-r9.5-design MOVE-1 and MOVE-2 (LD-Q-135). It is generated by `make_erratum_v2.py` and rides in r9.6 as s4, under the verdict line '
       '`C2B1A-MOVE: ACCEPT | REQUIRED-FINDINGS`.',
       '',
       '**What moves:** pure items, byte-identical, into lower crates. Each old file re-exports every moved item at its old '
       'path, at its old visibility. So every caller that names a moved ITEM by its old path compiles unchanged; a caller '
       'outside the new crate that reads a FIELD needs that field to be `pub`, which is exactly the declared field deltas below '
       '(LD-Q-135 MOVE-1).',
       '',
       '**What may differ inside a moved item, and nothing else:**',
       '- **item and method visibility:** `pub(crate)` or none becomes `pub`, because a crate boundary cannot re-export `pub(crate)`. '
       'The checker erases visibility ONLY at item and method positions.',
       '- **field visibility:** compared token by token. A widening is allowed only as a declared `field_deltas` entry '
       '(field, old, new, the reason, and every reading or constructing site outside the new crate). Every other field keeps its old visibility.',
       '- **declared per-row deltas** (`deltas` in the map): `seal` means a `crate::sealed::Sealed` supertrait (S.9).',
       '',
       '**Proof:** `move_identity.py` lexes each item (doc comments kept; whitespace and plain comments dropped), removes '
       'only the tokens above, and requires equality. Its negative controls (one token changed) report DIFFERS.',
       '']
for spec in args:
    title, mp, ident = spec.split('=')
    rows = json.load(open(mp))
    out += [f'## {title}', '', f'Map: `{Path(mp).name}`. Identity: `{Path(ident).name}`: '
            f'**{Path(ident).read_text().strip().splitlines()[-1]}**.', '',
            '| item | old visibility | old location | new location | deltas |', '|---|---|---|---|---|']
    for r in rows:
        fd = ', '.join(f"field `{d['field']}` {d['old']}->{d['new']}" for d in r.get('field_deltas', []))
        status = r.get('status', 'MOVED')
        out.append(f"| `{r['name']}` | {r['visibility']} | `{r['old']}` | `{r['new']}` | {', '.join(r.get('deltas', []) + ([fd] if fd else []) + ([status] if status != 'MOVED' else [])) or '-'} |")
    out.append('')
    fds = [(r['name'], d) for r in rows for d in r.get('field_deltas', [])]
    if fds:
        out += ['**Declared field deltas** (LD-Q-135 MOVE-1):', '', '| item | field | old | new | reason | read or constructed at |', '|---|---|---|---|---|---|']
        for name, d in fds:
            out.append(f"| `{name}` | `{d['field']}` | {d['old']} | {d['new']} | {d['reason']} | {', '.join('`'+x+'`' for x in d['read_at'])} |")
        out.append('')
out += ['## Citations of moved lines (resolved by item name at each document\'s pin)', '',
        '| document line | cited | at | item | new location |', '|---|---|---|---|---|']
for c in cites:
    for line in Path(c).read_text().splitlines():
        if 'MOVED' not in line:
            continue
        doc, cited, at, name, _, _, new = line.split(None, 6)
        out.append(f'| {doc} | `{cited}` | {at} | `{name}` | `{new}` |')
out += ['', 'Citations that resolve to items that stay are not listed. The full output, including STAYS, is in the '
        'citation files beside this erratum.', '']
if premises:
    import subprocess
    repo, (old_c, new_c) = '.', premises
    def premise_rows(commit):
        text = subprocess.run(['git', 'show', f'{commit}:crates/host/src/typescript_context_price_premises.rs'],
                              capture_output=True, text=True).stdout
        if not text:
            text = subprocess.run(['git', 'show', f'{commit}:crates/host/src/typescript_context_metered_tables/premises.rs'],
                                  capture_output=True, text=True).stdout
        import re as _re
        return dict(_re.findall(r'"([^"]+)",\s*"([0-9a-f]{64})"', text))
    a, b = premise_rows(old_c), premise_rows(new_c)
    out += ['## F1 premises re-pinned by the move (for F1\'s premise reconciliation, LD-Q-130-B)', '',
            f'Old at `{old_c}`, new at `{new_c}`; a premise added by the move has no old hash.', '',
            '| premise | old sha256 | new sha256 |', '|---|---|---|']
    for path in sorted(set(a) | set(b)):
        if a.get(path) != b.get(path):
            out.append(f"| `{path}` | `{a.get(path, '(new premise)')}` | `{b.get(path, '(removed)')}` |")
    out.append('')
Path(sys.argv[1]).write_text('\n'.join(out))
print(len(out), 'lines')
