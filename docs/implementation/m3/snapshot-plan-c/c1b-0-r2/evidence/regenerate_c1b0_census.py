"""C1b-0 r2 (Codex C1B0-R1-RF-1): the census transition from the accepted batch-entry baseline. Run after prepare and
generation, on the candidate worktree. Opens no held-out material and runs no blind mode.
  1. The baseline (C1b plan r3 LD-C1B-7; the Q5 ruling): on product main, which must hold C1a4's accepted blind
     refresh, BOTH receipts are current for main's own inputs, by the tools' own binding functions (discovery's
     receipt_bindings and the companion's Census.bindings), and both records render every held-out row from them
     ('blind-census'). Otherwise this script stops: the batch-entry baseline is not yet available.
  2. The regeneration: the candidate's discovery census and snapshot census records are regenerated by the tools'
     ordinary --write modes over the lead-readable cache (which never open a held-out store). The two receipts are
     not touched: each stays byte-equal to main's, preserved as historical baseline evidence for the stale interval.
  3. The record of the change: which outputs changed (the two records, and nothing else); and, field by field, that
     every change is the held-out rendering: the held-out rows from 'blind-census' to 'outstanding: held-out (blind
     receipt stale)', heldOutMargin to 'outstanding', and the fields the tools derive from the held-out results
     (discovery's failingEntries, the snapshot census's failing2x and capsStatus). Any other change fails.
Usage: regenerate_c1b0_census.py <out json> [--baseline-only | --verify]: --baseline-only checks the baseline alone (exit 2
while it is not yet available); --verify writes nothing and checks the candidate's records as they stand (the lane's
stale-receipt row)."""
from pathlib import Path
import hashlib, importlib.util, json, os, subprocess, sys
A = Path('/Users/sb/code/opensip-ai/opensip_arch'); P = A.parent / 'opensip'; W = A.parent / 'opensip-c1b0'
PY = '/opt/homebrew/Cellar/python@3.14/3.14.6/bin/python3.14'
T2 = '/Users/sb/code/.opensip-implementation-cache/t2-corpus-c8cc48e1'
STALE = 'outstanding: held-out (blind receipt stale)'
E = dict(os.environ, GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL='/dev/null')
for k in ('GIT_CONFIG_COUNT', 'GIT_DIR', 'GIT_WORK_TREE'): E.pop(k, None)
def load(root, name, rel):
    s = importlib.util.spec_from_file_location(name, root / rel); m = importlib.util.module_from_spec(s); s.loader.exec_module(m); return m
def read(root, rel): return json.loads((root / rel).read_bytes())
def pin(root, rel): b = (root / rel).read_bytes(); return dict(path=rel, bytes=len(b), sha256=hashlib.sha256(b).hexdigest())

dc_p = load(P, 'c1b0_dc_base', 'tools/security/discovery_census.py'); sc_p = load(P, 'c1b0_sc_base', 'tools/security/snapshot_ledger_census.py')
D_REC, D_RECEIPT = dc_p.OUTPUT_CENSUS, dc_p.OUTPUT_RECEIPT
S_REC, S_RECEIPT = sc_p.OUTPUT, sc_p.OUTPUT_RECEIPT
BASELINE_ONLY = '--baseline-only' in sys.argv[2:]; VERIFY = '--verify' in sys.argv[2:]
head = lambda root: subprocess.check_output(['/usr/bin/git', 'rev-parse', 'HEAD'], cwd=root, env=E).decode().strip()
if not BASELINE_ONLY:
    assert head(W) == head(P), 'the candidate must be rebuilt on main (prepare_c1b0.py --rebuild) first'
    for rel in ('tools/security/discovery_census.py', 'tools/security/snapshot_ledger_census.py', D_RECEIPT, S_RECEIPT):
        assert (W / rel).is_file() == (P / rel).is_file() and (not (P / rel).is_file() or (W / rel).read_bytes() == (P / rel).read_bytes()), rel
def companion_bindings(root, sc):
    return sc.Census(root, A, packages_root=P).bindings()
def held_rows(record_rel, record):
    if record_rel == D_REC:
        return [e for e in record['entries'] if isinstance(e.get('status'), str) and (e['status'].startswith('outstanding') or e['status'] == 'blind-census')]
    return record['heldOutEntries']

# 1. The baseline.
out = dict(productMain=subprocess.check_output(['/usr/bin/git', 'rev-parse', 'HEAD'], cwd=P, env=E).decode().strip())
base_d = dc_p.receipt_bindings(P, A, dc_p.costs(P)); stored_d = read(P, D_RECEIPT)['bindings']
base_s = companion_bindings(P, sc_p); stored_s = read(P, S_RECEIPT)['bindings'] if (P / S_RECEIPT).is_file() else None
base_records = {D_REC: read(P, D_REC), S_REC: read(P, S_REC)}
baseline = dict(discoveryReceipt=pin(P, D_RECEIPT), companionReceipt=pin(P, S_RECEIPT) if (P / S_RECEIPT).is_file() else None,
                discoveryReceiptCurrent=stored_d == base_d, companionReceiptCurrent=stored_s == base_s,
                discoveryRendered=sorted({r['status'] for r in held_rows(D_REC, base_records[D_REC])}), discoveryHeldOutMargin=base_records[D_REC]['heldOutMargin'],
                snapshotRendered=sorted({r['status'] for r in held_rows(S_REC, base_records[S_REC])}), snapshotHeldOutMargin=base_records[S_REC]['heldOutMargin'])
out['baseline'] = baseline
ready = (baseline['discoveryReceiptCurrent'] and baseline['companionReceiptCurrent'] and baseline['discoveryRendered'] == ['blind-census']
         and baseline['snapshotRendered'] == ['blind-census'])
out['baselineAvailable'] = ready
if not ready or BASELINE_ONLY:
    Path(sys.argv[1]).write_text(json.dumps(out, indent=2) + '\n')
    print(json.dumps(dict(baselineAvailable=ready, baseline={k: v for k, v in baseline.items() if 'Receipt' not in k or 'Current' in k})))
    sys.exit(0 if ready else 2)

# 2. The regeneration, by the candidate's own tools in their ordinary modes.
# The records compared are main's (the baseline's); --verify writes nothing and checks the candidate's records as they
# stand (the lane's stale-receipt row; the output --checks separately prove they are what the tools generate).
before = {rel: (P / rel).read_bytes() for rel in (D_REC, S_REC, dc_p.OUTPUT_VECTORS)}
tracked_before = subprocess.check_output(['/usr/bin/git', 'status', '--porcelain'], cwd=W, env=E).decode()
if not VERIFY:
    for tool in ('tools/security/discovery_census.py', 'tools/security/snapshot_ledger_census.py'):
        r = subprocess.run([PY, '-I', '-B', tool, '--write', '--architecture', str(A), '--packages-root', str(P), '--t2-cache', T2], cwd=W, env=E, capture_output=True)
        assert r.returncode == 0, (tool, r.stderr[-2000:])
tracked_after = subprocess.check_output(['/usr/bin/git', 'status', '--porcelain'], cwd=W, env=E).decode()
changed = sorted(rel for rel, raw in before.items() if (W / rel).read_bytes() != raw)
newly = sorted(l for l in set(tracked_after.splitlines()) - set(tracked_before.splitlines()) if l.startswith('??'))
for rel in (D_RECEIPT, S_RECEIPT): assert (W / rel).read_bytes() == (P / rel).read_bytes(), rel

# 3. The record of the change.
cand_d = load(W, 'c1b0_dc_cand', 'tools/security/discovery_census.py').receipt_bindings(W, A, dc_p.costs(W))
cand_s = companion_bindings(W, load(W, 'c1b0_sc_cand', 'tools/security/snapshot_ledger_census.py'))
PIN_KEYS = {'path', 'bytes', 'sha256'}
def delta(x, y, at=''):
    """The differing bindings, down to whole values; a pin row (path, bytes, sha256) is one value."""
    if isinstance(x, dict) and isinstance(y, dict) and not (set(x) == PIN_KEYS and set(y) == PIN_KEYS):
        return [d for k in sorted(set(x) | set(y)) for d in delta(x.get(k), y.get(k), at + '/' + k)]
    if isinstance(x, list) and isinstance(y, list) and len(x) == len(y):
        return [d for i, (u, v) in enumerate(zip(x, y)) for d in delta(u, v, at + '/' + str(i))]
    return [] if x == y else [dict(at=at, base=x, candidate=y)]
closure = 'tools/contracts/generator-closure.json'
d_delta, s_delta = delta(base_d, cand_d), delta(base_s, cand_s)
out['discoveryBindingDelta'] = d_delta; out['companionBindingDelta'] = s_delta
exact_d = len(d_delta) == 1 and d_delta[0]['base'] == dc_p.pin_row(P, closure) and d_delta[0]['candidate'] == dc_p.pin_row(W, closure)
exact_s = len(s_delta) == 1 and s_delta[0]['at'] == '/discovery' + d_delta[0]['at'] and s_delta[0]['base'] == d_delta[0]['base'] and s_delta[0]['candidate'] == d_delta[0]['candidate'] if exact_d else False
ALLOWED = {D_REC: {'entries', 'heldOutMargin', 'failingEntries'}, S_REC: {'heldOutEntries', 'heldOutMargin', 'failing2x', 'capsStatus'}}
fields = {}
for rel in (D_REC, S_REC):
    old, new = json.loads(before[rel]), read(W, rel)
    keys = sorted(k for k in set(old) | set(new) if old.get(k) != new.get(k))
    rows_old, rows_new = held_rows(rel, old), held_rows(rel, new)
    held_ids = sorted(r['id'] for r in rows_old)
    if rel == D_REC:   # only held-out rows of `entries` may change
        o = {e['id']: e for e in old['entries']}; n = {e['id']: e for e in new['entries']}
        non_held = sorted(i for i in set(o) | set(n) if o.get(i) != n.get(i) and i not in held_ids)
    else:
        non_held = []
    fields[rel] = dict(changedKeys=keys, nonHeldOutRowsChanged=non_held, heldOutRows=len(rows_new),
                       renderedAfter=sorted({r['status'] for r in rows_new}), heldOutMarginAfter=new['heldOutMargin'],
                       before=dict(bytes=len(before[rel]), sha256=hashlib.sha256(before[rel]).hexdigest()), after=pin(W, rel))
out['records'] = fields
ok = (exact_d and exact_s and changed == sorted([D_REC, S_REC]) and newly == [] and all(
    set(f['changedKeys']) <= ALLOWED[rel] and not f['nonHeldOutRowsChanged'] and f['renderedAfter'] == [STALE] and f['heldOutMarginAfter'] == 'outstanding'
    for rel, f in fields.items()))
out.update(mode='verify' if VERIFY else 'write', outputsChanged=changed, untrackedAdded=newly, receiptsPreservedByteEqualMain=True, exactlyTheClosureDigest=exact_d,
           companionExactlyTheNestedClosureDigest=exact_s, passed=ok)
Path(sys.argv[1]).write_text(json.dumps(out, indent=2) + '\n')
print(json.dumps({k: out[k] for k in ('baselineAvailable', 'outputsChanged', 'exactlyTheClosureDigest', 'companionExactlyTheNestedClosureDigest', 'passed')}))
sys.exit(0 if ok else 1)
