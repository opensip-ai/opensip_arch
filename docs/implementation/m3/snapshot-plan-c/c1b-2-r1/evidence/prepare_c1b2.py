"""C1b-2 r1 preparation, on the candidate worktree at product main with C1b-1 integrated (re-runnable): the snapshot
census record regenerated by its tool's own --write mode over the lead-readable cache (which never opens a held-out
store); the charge model and the discovery census are checked unchanged (C1b-2 adds no model term and changes no
discovery input, C1b plan r6 LD-C1B-6 and LD-C1B-7). The two receipts are never written. It then requires the
candidate's changed paths to be exactly the unit's. Usage: prepare_c1b2.py <out json>."""
from pathlib import Path
import hashlib, json, os, subprocess, sys
A = Path('/Users/sb/code/opensip-ai/opensip_arch'); P = A.parent / 'opensip'; W = A.parent / 'opensip-c1b2'
PY = '/opt/homebrew/Cellar/python@3.14/3.14.6/bin/python3.14'
T2 = '/Users/sb/code/.opensip-implementation-cache/t2-corpus-c8cc48e1'
RECEIPTS = ('crates/security/src/custody/discovery_census_held_out.json', 'crates/security/src/snapshot_ledger_census_held_out.json')
EXPECTED = sorted(['crates/host/src/snapshot_seal.rs', 'crates/host/src/snapshot_seal_tests.rs',
                   'crates/security/src/snapshot_ledger_census.json', 'tools/security/snapshot_ledger_census.py'])
E = dict(os.environ, GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL='/dev/null')
for k in ('GIT_CONFIG_COUNT', 'GIT_DIR', 'GIT_WORK_TREE'): E.pop(k, None)
def git(root, *a): return subprocess.check_output(['/usr/bin/git', *a], cwd=root, env=E).decode().strip()
def pin(root, p): raw = (root / p).read_bytes(); return dict(path=p, bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest())
assert git(W, 'rev-parse', 'HEAD') == git(P, 'rev-parse', 'HEAD'), 'rebuild the worktree on main first'
assert (P / 'crates/security/src/snapshot_vcs.rs').is_file(), 'C1b-1 must be on main'
receipts = {r: (W / r).read_bytes() for r in RECEIPTS}
cache = ['--architecture', str(A), '--packages-root', str(P), '--t2-cache', T2]
steps = [[PY, '-I', '-B', 'tools/security/snapshot_ledger_model.py', '--check', '--architecture', str(A), '--packages-root', str(P)],
         [PY, '-I', '-B', 'tools/security/discovery_census.py', '--check', *cache],
         [PY, '-I', '-B', 'tools/security/snapshot_ledger_census.py', '--write', *cache]]
logs = []
for cmd in steps:
    r = subprocess.run(cmd, cwd=W, env=E, capture_output=True)
    assert r.returncode == 0, (cmd, r.stderr[-2000:])
    logs.append(dict(command=' '.join(cmd[3:5]), stdout=r.stdout.decode()[-600:]))
for r, b in receipts.items(): assert (W / r).read_bytes() == b, r
changed = sorted(git(W, 'diff', '--name-only').splitlines() + git(W, 'ls-files', '--others', '--exclude-standard').splitlines())
out = dict(productBase=git(W, 'rev-parse', 'HEAD'), steps=logs, changed=changed, receiptsUnchanged=True, passed=changed == EXPECTED,
           candidates=[pin(W, p) for p in changed])
Path(sys.argv[1]).write_text(json.dumps(out, indent=2) + '\n')
print(json.dumps(dict(productBase=out['productBase'], changed=changed, passed=out['passed'])))
raise SystemExit(0 if out['passed'] else 1)
