"""TSR-1 r1: build the closed compilerOptions classification table from TypeScript 6.0.3's own declarations.

Usage: python3 -I classify_options.py ts-6.0.3-option-declarations.json > option-table.md
Checks that every declared name is classified exactly once and that no classified name is undeclared.
"""
import json, sys

HONORED = ["allowJs", "allowSyntheticDefaultImports", "baseUrl", "checkJs", "customConditions", "esModuleInterop",
           "jsx", "lib", "module", "moduleResolution", "noEmit", "paths", "resolveJsonModule", "rootDirs",
           "skipLibCheck", "strict", "target", "types"]
PINNED = {
    "allowArbitraryExtensions": "`false`",
    "isolatedModules": "`false`",
    "jsxImportSource": "`\"react\"`, only when effective `jsx` is `react-jsx` or `react-jsxdev`",
    "libReplacement": "`false`",
    "maxNodeModuleJsDepth": "the unwritten value: `2` when the graph has a `jsconfig` node, else `0`",
    "moduleDetection": "the computed default only, matched by `fold`: `force` when effective `module` is `node16`, `node18`, `node20` or `nodenext`, otherwise `auto`",
    "moduleSuffixes": "`[\"\"]`",
    "noLib": "`false`",
    "noResolve": "`false`",
    "preserveSymlinks": "`false`",
    "resolvePackageJsonExports": "any boolean when effective `moduleResolution` is `node10` or `classic` (the compiler forces `false`); otherwise `true`",
    "resolvePackageJsonImports": "any boolean when effective `moduleResolution` is `node10` or `classic` (the compiler forces `false`); otherwise `true`",
    "typeRoots": "none",
    "verbatimModuleSyntax": "`false`",
}
EMITS = {"declaration", "declarationMap", "emitDeclarationOnly", "sourceMap", "inlineSourceMap", "outFile", "outDir",
         "removeComments", "importHelpers", "downlevelIteration", "sourceRoot", "mapRoot", "inlineSources", "emitBOM",
         "newLine", "stripInternal", "noEmitHelpers", "noEmitOnError", "preserveConstEnums", "declarationDir",
         "rootDir", "composite", "incremental", "tsBuildInfoFile", "generateCpuProfile", "generateTrace"}
EXECUTABLE = {"plugins"}

def main(path, as_json=False):
    d = json.load(open(path))
    assert d["version"] == "6.0.3", d["version"]
    names = sorted({o["name"] for o in d["options"]}, key=lambda s: s.encode())
    declared = set(names)
    for group in (HONORED, PINNED, EMITS, EXECUTABLE):
        missing = set(group) - declared
        assert not missing, missing
    rows = []
    for n in names:
        if n in HONORED:
            rows.append((n, "H", "honored (TSR-1 §1)"))
        elif n in PINNED:
            rows.append((n, "P", "pinned; admitted written values: " + PINNED[n]))
        elif n in EMITS:
            rows.append((n, "S", "`emits-output`"))
        elif n in EXECUTABLE:
            rows.append((n, "S", "`selects-an-executable`"))
        else:
            rows.append((n, "S", "`not-a-resolution-or-membership-option`"))
    assert len(rows) == len(names)
    if as_json:
        print(json.dumps([{"name": n, "class": c, "rule": r} for n, c, r in rows], indent=1)); return
    print(f"<!-- generated by work/evidence/classify_options.py from TypeScript {d['version']} declarations; {len(rows)} names -->")
    print("| `compilerOptions` member | Class | Rule |")
    print("|---|---|---|")
    for n, c, r in rows:
        print(f"| `{n}` | {c} | {r} |")
    counts = {c: sum(1 for _, k, _ in rows if k == c) for c in "HPS"}
    print(f"\nCounts: H {counts['H']}, P {counts['P']}, S {counts['S']}; total {len(rows)}.", file=sys.stderr)

main(sys.argv[1], len(sys.argv) > 2 and sys.argv[2] == "--json")
