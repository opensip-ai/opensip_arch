"""TSR-1 r1: build the lib canonicalization table (T-LIB) and the target-default table (T-DEF) from TypeScript 6.0.3.

Usage: python3 -I lib_tables.py ts-6.0.3-lib-data.json <typescript package lib dir> > lib-tables.md
"""
import json, re, sys
d = json.load(open(sys.argv[1])); libdir = sys.argv[2]
assert d["version"] == "6.0.3"
REF = re.compile(r'^/// <reference lib="([^"]+)" />\s*$')
def stem(f):
    assert f.startswith("lib.") and f.endswith(".d.ts"), f
    return f[4:-5]
print("<!-- generated by work/evidence/lib_tables.py from TypeScript 6.0.3 libMap, targetToLibMap and lib files -->")
print("**T-LIB (lib name canonicalization).** Key = `fold(written)`; value = canonical name `c` (so `component(c)` is TypeScript's own file).\n")
print("| Written name (folded) | Canonical name |"); print("|---|---|")
for k, f in d["libMap"]:
    print(f"| `{k}` | `{stem(f)}` |")
names = {k for k, _ in d["libMap"]}
print("\n**T-DEF (target-default lib list).** Key = effective canonical `target`; value = the `lib` list, in order.\n")
print("| Effective `target` | TypeScript default file | Materialized `honoredOptions.lib` |"); print("|---|---|---|")
seen = set()
for key, val, deff in d["targets"]:
    if key in ("es6", "es3"):  # es6 is an alias of es2015; es3 computes to es2025 (TSR-1 §1)
        continue
    refs = []
    text = open(f"{libdir}/{deff}", encoding="utf-8").read()
    body = re.sub(r"/\*.*?\*/", "", text, flags=re.S)  # the license block comment
    for line in body.splitlines():
        if line.startswith("///"):
            m = REF.match(line); assert m, line; refs.append(m.group(1))
        else:
            assert not line.strip(), (deff, line)  # the file holds nothing but reference directives
    for r in refs:
        assert r in names and dict(d["libMap"])[r] == f"lib.{r}.d.ts", r   # every referenced name is already canonical
    print(f"| `{key}` | `{deff}` | `[{', '.join(repr(r).replace(chr(39), chr(34)) for r in refs)}]` |")
