"""Cross-implementation vectors for the D15 readers and membership decision (M3-B r9 items 19 to 24; unit B3-b2b1, plan r2
amendment A2; regenerated by unit B3-b2b2b r3 under amendment A4).

Developer tool only. It runs B3-b0 r4, the members-and-readers reference (contract successor 169), at its bound bytes
over its own checker's D15 cases (`b3-b-reference-r4/evidence/check.py`, `d15_cases`) and over every discovery case of
security/discovery-cases.v1.json (none declares a member), and writes or checks
crates/security/src/workspace_member_vectors.json. No case is written here.

The decision core (`workspace_declarations.rs`) is B3-b0's `discover` without SLM's two passes, so each vector records,
by wrapping the reference's `_finish` and `_refuse` (their bytes unchanged), what the core decides and what it is
given:
  * `observation`: the synthetic tree below W, keyed W-relative (`""` is W), with the carrier and manifest bytes, the VCS
    side table, item 6b's supplied verdicts and (r4) its index gitlinks; W2 (no VCS marker at W or an ancestor, item
    6a's NoRepository) and the invocation facts (invoking user, groups, the owner waiver, the workspace-roots array and
    its source);
  * `walk`: in branch A, when the reference reaches its one walk (A4-2 step 3), the admitted members and their W-relative
    gitlinks that walk was given, and its status;
  * `expected`: the outcome. `members` (with `declaredBy`), `declarations` (the `workspaceDeclarations` rows) and
    `links` for a decided member set; a member-rule refusal's code, path and detail with the rows of the discovery
    without members; (r4) `array-refused`, the gate's record, with the root's raw text as its path; or `walk-refused`
    with the rows as they stood at the walk;
  * `sixB`: (r4) every candidate whose item-6b verdict or gitlinks the reference consulted, W-relative;
  * `consulted` and `read`: every W-relative path the reference's reader code looked up (`_entry`) or read (`contents`),
    so the security test can assert that the core consults nothing else (B3B0REF-R2-RF-1's spy); `listed`: every
    directory its glob walk listed (r2, B3B2B1-R1-RF-3: W and each child it queued); `forbidden`: the checker case's own
    `notObserved` paths, which the core must never touch (A2 r2, B3BA2-R1-RF-2); and (r4) `forbiddenReads`: its
    `notRead` paths, which the core must never read. A by-name lookup of a `notRead` path is the reference's own where
    placement passes it (B3-b0 r4 LD-B3B0-16), so it is held to the `consulted` comparison instead.
Parser controls (A2 r2, B3BA2-R1-RF-1) follow the cases, labelled `control:`. JSON controls must equal the reference.
TOML controls exceed parse_toml's local bounds in an unrelated field of an otherwise usable carrier or provider manifest:
`tomllib` reads them (`referenceExpected`), and the product's `expected` is the existing `parse` disposition, computed
by running the reference over the same input with that file's bytes replaced by unparseable TOML (the carrier's digest
is the real bytes'). A large content is stored as `{"parts": [text | [unit, count], ...]}`.
Cases with no selected root (no W, so no carrier), the side-table consistency controls and (r4) the gate's non-string
roots, which a product array of strings cannot hold, are listed by id only.
No filesystem tree, network or environment input.
"""
