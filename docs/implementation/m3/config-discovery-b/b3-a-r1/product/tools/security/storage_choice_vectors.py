"""Cross-implementation byte vectors for S3.1's backup custody choice (M3-B r5 item 23; unit B3-a).

Developer tool only. It runs SLM `storage_write_admission`, the accepted reference, at its accepted architecture
bytes over every combination of its inputs and writes or checks crates/security/src/storage_choice_vectors.json:
each case's inputs and SLM's result. The product test pins those results.

SLM loads its schema bundle, canonical.py (which imports jsonschema) and discovery-defaults.py when imported; each
is pinned, and the tool imports the product's provisioned jsonschema snapshot only after every file matches its
generator-closure pin. No network or environment input.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import itertools
import json
import sys

OUTPUT = 'crates/security/src/storage_choice_vectors.json'
DESIGN = 'docs/coop/design-corrections/'
# Architecture inputs (each a member of candidate-subject.v45.json): path, bytes, SHA-256.
ARCH = (
    (DESIGN + 'security/security_lifecycle_model_v1.py', 208076, 'd0ef9814d27b86f10bdc1aa9a9a4781124c93c3dd92eeecdfe3090fe21d18bb9'),
    (DESIGN + 'security/security-lifecycle.schemas.v1.json', 135672, 'f66d2c617084825e3cdb9a855a151c10aa66625968b40ef91fc6bb3be39423f4'),
    (DESIGN + 'foundation/canonical.py', 6465, 'd47f25db0fb09ceb84282a89fdf74055cb81ccb9de26f85a5a70b032b9a6b442'),
    (DESIGN + 'discovery-defaults.py', 22344, 'f30b68502b6fb70992eb4e9fe4dbd6919df69180e020d6f2e1538f7fa8cfb28c'),
)
RECORD = '0123456789abcdef' * 4
# Admitted storage-policy record inputs: absent, the grammar's one lawful form, and malformed spellings that
# neither SLM nor the product admits. SLM's Python `$` also matches before a trailing newline; the product's
# record id is the schema grammar and refuses it, so that spelling is a product-only test, not a vector.
RECORDS = (None, RECORD, RECORD.upper(), RECORD[:63], 'g' * 64, '')
BACKUP = ('BACKED_UP', 'NOT_BACKED_UP', 'UNKNOWN')


def require(condition, message):
    if not condition:
        raise ValueError(message)


def pinned(root, path, size, digest):
    raw = (root / path).read_bytes()
    require(len(raw) == size and hashlib.sha256(raw).hexdigest() == digest, 'input pin mismatch: ' + path)
    return raw


def packages(product, packages_root):
    closure = json.loads((product / 'tools/contracts/generator-closure.json').read_bytes())
    rows = [r for r in closure['files'] if r['path'].startswith('tools/contracts/python-packages/')]
    require(rows, 'no pinned python packages')
    for row in rows:
        pinned(packages_root, row['path'], row['bytes'], row['sha256'])
    sys.path.insert(0, str(packages_root / 'tools/contracts/python-packages'))


def model(arch):
    for row in ARCH:
        pinned(arch, *row)
    spec = importlib.util.spec_from_file_location('slm', arch / ARCH[0][0])
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run(module):
    out = []
    for backup, ephemeral, flag, record, ci in itertools.product(BACKUP, (False, True), (False, True), RECORDS, (False, True)):
        result = module.storage_write_admission(backup, flag, record, ci, ephemeral)
        out.append({'backup': backup, 'ephemeral': ephemeral, 'allowBackupCustody': flag,
                    'admittedPolicyRecord': record, 'ci': ci,
                    'slm': {k: result[k] for k in ('result', 'choice', 'refusal', 'detail', 'd9',
                                                   'policyFileWritten', 'rootIdentityChanged')}})
    return out


def vectors(arch, product, packages_root):
    packages(product, packages_root)
    module = model(arch)
    body = {'schemaVersion': 1,
            'standing': 'SLM byte vectors for the product S3.1 choice (M3-B r5 item 23). Generated by '
                        'tools/security/storage_choice_vectors.py from SLM storage_write_admission at its accepted '
                        'bytes; design reference results, not product qualification.',
            'sources': [{'path': p, 'bytes': n, 'sha256': d} for p, n, d in ARCH],
            'cases': run(module)}
    return (json.dumps(body, indent=1, ensure_ascii=True) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true', help='compare the output without writing repository files')
    mode.add_argument('--write', action='store_true', help='regenerate the output')
    parser.add_argument('--architecture', type=Path, required=True, help='architecture checkout holding SLM')
    parser.add_argument('--packages-root', type=Path, required=True,
                        help='checkout holding the provisioned tools/contracts/python-packages snapshot')
    args = parser.parse_args()
    product = Path(__file__).resolve().parent.parent.parent
    raw = vectors(args.architecture.resolve(strict=True), product, args.packages_root.resolve(strict=True))
    target = product / OUTPUT
    if args.check:
        require(target.is_file() and target.read_bytes() == raw, 'vectors differ: ' + OUTPUT)
    else:
        target.write_bytes(raw)
    print(('Verified ' if args.check else 'Generated ') + OUTPUT + ' from SLM at its accepted bytes.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, TypeError, OSError) as error:
        print(f'Storage choice vector generation failed: {error}', file=sys.stderr)
        raise SystemExit(1)
